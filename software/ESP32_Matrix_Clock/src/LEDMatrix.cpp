void LEDMatrix::drawBigString(const char *string, int len, int x, int y, uint8_t whitespace)
{
   int currentX = x;
   for (int charIdx = 0; charIdx < len; charIdx++)
   {
      if (currentX < 32)
      {
         char c = string[charIdx];
         uint8_t cFontWidth = drawBigChar(c, currentX, y);
         currentX += cFontWidth;
         for (int s = 0; s < whitespace; s++)
         {
            setColumn(currentX + s, 0x00);
         }
         currentX += whitespace;
      }
   }
}

uint8_t LEDMatrix::drawBigChar(char c, int x, int y)
{
   int currentX = x;
   int asc = c - 32;
   uint8_t fontWidth = pgm_read_byte(&(font8x8[asc][0]));
   fontWidth -= 2;
   for (int r = 0; r < 8; r++)
   {
      uint8_t row = pgm_read_byte(&(font8x8[asc][r + 1]));
      row <<= (8 - fontWidth);
      for (int w = 0; w < fontWidth; w++)
      {
         if (((currentX + w) < 32) && ((y + r) < 8))
         {
            setPixel(currentX + w, y + r, row & (0x80 >> w));
         }
         else
         {
            continue;
         }
      }
   }
   return fontWidth;
}

